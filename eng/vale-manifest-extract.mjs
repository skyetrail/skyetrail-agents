// Vale's [*.md] scope never reaches plugin.json or marketplace.json, but both
// carry a description field that the generated READMEs quote directly. This
// script pulls every such field into one markdown file, named by its exact
// source, so `npm run vale` covers manifest prose the same way it already
// covers a SKILL.md's frontmatter description.
//
//   node eng/vale-manifest-extract.mjs   writes .vale/manifests.md
//
// Plain Node ESM, no dependencies, matching every other script here.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function read(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

const lines = [
  "<!-- Generated by eng/vale-manifest-extract.mjs. Do not edit this file by hand. -->",
  "",
  "# Manifest prose",
  "",
  "Every free-text field from plugin.json and marketplace.json, extracted so",
  "`npm run vale` can check it. Fix the source field, not this file.",
  "",
];

const marketplacePath = path.join(ROOT, "marketplace.json");
if (fs.existsSync(marketplacePath)) {
  const mp = read(marketplacePath);
  if (mp.metadata?.description) {
    lines.push("## marketplace.json: metadata.description", "", mp.metadata.description, "");
  }
  for (const entry of mp.plugins ?? []) {
    if (entry.description) {
      lines.push(`## marketplace.json: plugins[${entry.name}].description`, "", entry.description, "");
    }
  }
}

const pluginsDir = path.join(ROOT, "plugins");
if (fs.existsSync(pluginsDir)) {
  for (const name of fs.readdirSync(pluginsDir).sort()) {
    const pluginJsonPath = path.join(pluginsDir, name, "plugin.json");
    if (!fs.existsSync(pluginJsonPath)) continue;
    const pkg = read(pluginJsonPath);
    if (pkg.description) {
      lines.push(`## plugins/${name}/plugin.json: description`, "", pkg.description, "");
    }
  }
}

const outDir = path.join(ROOT, ".vale");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "manifests.md"), lines.join("\n"));
console.log(`Wrote ${path.relative(ROOT, path.join(outDir, "manifests.md"))}`);
